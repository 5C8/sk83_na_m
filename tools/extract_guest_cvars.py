#!/usr/bin/env python3
"""Extract the guest game's cVar registry from the recompiled sources.

The game registers every debug variable through a cVar*Ref constructor at
static-init time. The recompiler emits one function per cVar, named after it,
with the PowerPC that sets up the call preserved as comments:

    // lis  r11,-32224          r11 = 0x82200000
    // addi r4,r11,64           r4  = 0x82200040  (category string)
    // addi r5,r4,-16           r5  = 0x82200030  (name string)
    // addi r6,r4,-32           r6  = 0x82200020  (description string)
    // addi r3,r10,-23296       r3  = the cVar OBJECT
    // bl 0x82d8a478            cVarBoolRef::cVarBoolRef(...)

We re-evaluate that register arithmetic to recover, per cVar: the object
address, the name/description/category string addresses, and the type. The
object itself is {vtable, value, category*, name*} -- so the console reads and
writes `object + 4` to change a variable live.

Output: a generated C++ header with the whole table.
"""
import re, sys, glob, os, struct

CTOR = {
    'cVarBoolRef':  'kBool',
    'cVarIntRef':   'kInt',
    'cVarFloatRef': 'kFloat',
    'cVarEnumRef':  'kEnum',
}

def s32(v):
    v &= 0xFFFFFFFF
    return v - (1 << 32) if v & 0x80000000 else v

def evaluate(lines):
    """Walk one initializer's commented PPC, yielding EVERY cVar it registers.

    One initializer can construct several cVars in sequence (the recompiler
    names the function after just the first), so collect them all and let the
    caller take each cVar's real name from the name string it points at.
    """
    regs = {}
    out = []
    for ln in lines:
        m = re.search(r'//\s*lis\s+r(\d+),(-?\d+)', ln)
        if m:
            regs[int(m.group(1))] = (int(m.group(2)) << 16) & 0xFFFFFFFF
            continue
        m = re.search(r'//\s*addi\s+r(\d+),r(\d+),(-?\d+)', ln)
        if m:
            d, a, imm = int(m.group(1)), int(m.group(2)), int(m.group(3))
            if a in regs:
                regs[d] = (regs[a] + imm) & 0xFFFFFFFF
            continue
        m = re.search(r'//\s*li\s+r(\d+),(-?\d+)', ln)
        if m:
            regs[int(m.group(1))] = int(m.group(2)) & 0xFFFFFFFF
            continue
        m = re.search(r'rex_\d*(cVar\w*Ref)_', ln)
        if m and m.group(1) in CTOR:
            out.append((CTOR[m.group(1)], dict(regs)))
    return out

def main(gen_dir, out_path):
    entries = []
    seen = set()
    for path in sorted(glob.glob(os.path.join(gen_dir, 'sk83_na_m_recomp.*.cpp'))):
        src = open(path, encoding='utf-8', errors='replace').read().splitlines()
        i = 0
        while i < len(src):
            m = re.match(r'DEFINE_REX_FUNC\((rex_\w*dynamic_initializer_for_(\w+?)_([0-9A-F]{8}))\)', src[i])
            if not m:
                i += 1
                continue
            cvar_name, addr_hex = m.group(2), m.group(3)
            body = src[i:i + 80]
            for kind, regs in evaluate(body):
                obj  = regs.get(3)
                name = regs.get(5)
                desc = regs.get(6)
                if obj and name and obj not in seen:
                    seen.add(obj)
                    entries.append((cvar_name, kind, obj, name, desc or 0,
                                    int(addr_hex, 16)))
            i += 1
    entries.sort(key=lambda e: e[0].lower())
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/extract_guest_cvars.py -- DO NOT EDIT.\n')
        f.write('// The guest game\'s debug variable registry, recovered from the\n')
        f.write('// recompiled static initializers. `object` is the cVar instance:\n')
        f.write('//   +0x00 vtable   +0x04 value   +0x08 category*   +0x0C name*\n')
        f.write('// so writing `object + 4` changes the variable live.\n')
        f.write('#pragma once\n#include <cstdint>\n\n')
        f.write('namespace skate3::guest_cvars {\n\n')
        f.write('enum class Kind : uint8_t { kBool, kInt, kFloat, kEnum };\n\n')
        f.write('struct Entry {\n'
                '  const char* name;\n'
                '  Kind kind;\n'
                '  uint32_t object;    // guest address of the cVar instance\n'
                '  uint32_t name_str;  // guest address of its name string\n'
                '  uint32_t desc_str;  // 0 when absent\n'
                '};\n\n')
        f.write(f'inline constexpr Entry kEntries[] = {{\n')
        for n, k, obj, nm, de, _ in entries:
            f.write(f'    {{"{n}", Kind::{k}, 0x{obj:08X}u, 0x{nm:08X}u, 0x{de:08X}u}},\n')
        f.write('};\n')
        f.write(f'inline constexpr uint32_t kEntryCount = {len(entries)};\n\n')
        f.write('}  // namespace skate3::guest_cvars\n')
    kinds = {}
    for _, k, *_rest in entries:
        kinds[k] = kinds.get(k, 0) + 1
    print(f'extracted {len(entries)} cvars -> {out_path}')
    for k, v in sorted(kinds.items()):
        print(f'   {k}: {v}')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
